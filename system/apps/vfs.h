#ifndef NEXUSOS_VFS_H
#define NEXUSOS_VFS_H

/* Простая виртуальная файловая система, живущая целиком в ОЗУ (статический
 * массив узлов, без malloc, без реального диска). Существует до
 * перезагрузки — как только появится настоящий драйвер диска и ФС
 * (Milestone 7/8), это можно будет заменить или оставить как ramfs. */

#define VFS_MAX_NODES   48
#define VFS_NAME_LEN    24
#define VFS_CONTENT_LEN 200

/* Инициализирует ФС: создаёт корневую директорию "/", переводит текущую
 * директорию в корень. Вызывать один раз при старте шелла. */
void vfs_init(void);

/* Создаёт директорию name в текущей директории.
 * 0 = успех, -1 = уже существует или нет свободных узлов. */
int vfs_mkdir(const char *name);

/* Создаёт пустой файл name в текущей директории. Коды возврата как у mkdir. */
int vfs_touch(const char *name);

/* Удаляет файл или ПУСТУЮ директорию name из текущей директории.
 * 0 = успех, -1 = не найдено или директория не пуста. */
int vfs_rm(const char *name);

/* Переходит в поддиректорию name текущей директории.
 * ".." — в родительскую (в корне не действует), "." — без изменений.
 * 0 = успех, -1 = такой директории нет. */
int vfs_cd(const char *name);

/* Печатает содержимое текущей директории (файлы и поддиректории). */
void vfs_ls(void);

/* Печатает полный путь текущей директории, например /home/docs. */
void vfs_pwd(void);

/* Печатает содержимое файла name из текущей директории, либо сообщение
 * об ошибке, если файла нет. */
void vfs_cat(const char *name);

/* Записывает content в файл name текущей директории (создаёт файл, если
 * его ещё нет; перезаписывает, если есть).
 * 0 = успех, -1 = нет свободных узлов или name — директория. */
int vfs_write(const char *name, const char *content);

/* Дописывает content в конец файла name текущей директории (создаёт
 * файл, если его ещё нет). 0 = успех, -1 = нет места или name — директория. */
int vfs_append(const char *name, const char *content);

/* Возвращает указатель на содержимое файла name текущей директории, или
 * NULL, если такого файла нет или это директория. Указатель действителен
 * до следующего изменения этого файла. */
const char *vfs_get_content(const char *name);

/* Удаляет ПУСТУЮ директорию name из текущей директории (в отличие от
 * vfs_rm, отказывает, если name — файл). 0 = успех, -1 = ошибка. */
int vfs_rmdir(const char *name);

/* Копирует файл src в новый файл dst внутри текущей директории.
 * Работает только с файлами (не с директориями). 0/-1 как обычно. */
int vfs_cp(const char *src, const char *dst);

/* Переименовывает файл или директорию src в dst внутри текущей директории
 * (перемещение между директориями не поддерживается). 0/-1 как обычно. */
int vfs_mv(const char *src, const char *dst);

/* Ищет по ВСЕЙ файловой системе (не только в текущей директории) узлы с
 * именем name и печатает их полный путь. */
void vfs_find(const char *name);

/* Считает суммарный размер (в байтах) и количество файлов во всём
 * поддереве текущей директории (рекурсивно). */
void vfs_du(unsigned int *out_bytes, unsigned int *out_files);

/* Считает, сколько узлов ФС занято и сколько всего доступно. */
void vfs_df(unsigned int *out_used, unsigned int *out_total);

/* Утилита: отделяет первое слово строки s от остатка по первому пробелу
 * (как это делает шелл для имени команды/аргументов). Модифицирует s на
 * месте (ставит '\0'), возвращает указатель на остаток строки (может
 * быть пустой строкой, если второго слова нет). */
char *vfs_split_word(char *s);

#endif /* NEXUSOS_VFS_H */
